"""Build a standalone deploy/ folder from the maintained application sources."""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

DEPLOY = Path(__file__).resolve().parent
ROOT = DEPLOY.parent
MARKER = ".hong-deploy-generated"


def source_files():
    backend = [ROOT/name for name in ("hong_core.py","hong_database.py","hong_tiktok.py",
               "backend/__init__.py","backend/api.py","backend/domain.py","backend/service.py",
               "database/mysql_schema.sql")]
    frontend = [ROOT/"frontend"/name for name in ("package.json","package-lock.json","index.html","vite.config.js")]
    frontend += sorted(p for p in (ROOT/"frontend"/"src").rglob("*") if p.is_file())
    public = ROOT/"frontend"/"public"
    if public.exists():
        frontend += sorted(p for p in public.rglob("*") if p.is_file())
    result = {}
    for service,files in (("backend",backend),("frontend",frontend)):
        base = ROOT/"frontend" if service == "frontend" else ROOT
        for path in files:
            if path.is_symlink() or not path.resolve().is_relative_to(base.resolve()):
                raise ValueError("Không đóng gói đường dẫn liên kết ra ngoài mã nguồn.")
            if path.name.startswith(".env") or path.suffix in {".sqlite3",".exe"} or path.name.startswith("cookies"):
                raise ValueError("Phát hiện file riêng tư trong danh sách đóng gói.")
            result[(service,path.relative_to(base))] = path
    return result


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepare(*,check=False):
    sources = source_files()
    manifest = {f"{service}/app/{relative.as_posix()}":digest(path)
                for (service,relative),path in sources.items()}
    if check:
        for name,expected in manifest.items():
            target = DEPLOY/name
            if not target.is_file() or target.is_symlink() or digest(target) != expected:
                raise ValueError("Bản deploy chưa được chuẩn bị hoặc đã cũ. Chạy python deploy/prepare.py.")
        print(f"Deploy khớp mã nguồn: {len(manifest)} file.")
        return manifest
    for service in ("backend","frontend"):
        target = DEPLOY/service/"app"
        expected = DEPLOY.resolve()/service/"app"
        if target.is_symlink() or target.resolve() != expected or not expected.is_relative_to(DEPLOY.resolve()):
            raise ValueError("Đường dẫn xuất không nằm trong thư mục deploy dự kiến.")
        if target.exists():
            if not (target/MARKER).is_file():
                raise ValueError(f"Không ghi đè thư mục chưa có dấu generated: {target}")
            # Exact, verified generated directory under deploy; never remove user env files.
            shutil.rmtree(target)
        target.mkdir(parents=True)
        (target/MARKER).write_text("Generated by deploy/prepare.py\n",encoding="utf-8")
    for (service,relative),path in sources.items():
        target = DEPLOY/service/"app"/relative
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(path,target)
    (DEPLOY/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
    print(f"Đã chuẩn bị deploy độc lập: {len(manifest)} file mã nguồn. Không chép .env, cookie hoặc dữ liệu local.")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    args = parser.parse_args()
    prepare(check=args.check)
